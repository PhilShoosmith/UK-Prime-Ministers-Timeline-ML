const fileContent = fs.readFileSync('services/gameService.ts', 'utf8');

let updatedContent = fileContent;
let matchCount = 0;

updatedContent = updatedContent.replace(/\{ "id": (\d+),.*?"contextZh": "(.*?)",/g, (match, idStr, contextZh) => {
  const id = parseInt(idStr, 10);
  const arContext = arContexts[id - 1];
  matchCount++;
  return `${match} "contextAr": "${arContext}",`;
});

fs.writeFileSync('services/gameService.ts', updatedContent);
